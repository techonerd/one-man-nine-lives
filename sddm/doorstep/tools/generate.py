def make_casper_tail_swish(is_dark: bool, frame: int) -> str:
    coat, outline, stroke_w, _, _, _, _, _ = get_casper_style(is_dark)
    angles = [0.0, 4.0, 8.0, 0.0, -4.0, -8.0]
    ang = angles[frame % 6]
    rad = math.radians(ang)
    bx, by = 15.0, 60.0
    c1x = 32.0 + 4.0 * math.sin(rad)
    c1y = 56.0
    c2x = 52.0 + 8.0 * math.sin(rad)
    c2y = 38.0 - 4.0 * math.cos(rad)
    tx = 42.0 + 12.0 * math.sin(rad)
    ty = 18.0 - 2.0 * math.cos(rad)
    path_d = f"M{bx:.1f} {by:.1f} C{c1x:.1f} {c1y:.1f} {c2x:.1f} {c2y:.1f} {tx:.1f} {ty:.1f}"

    outline_path = ""
    if not is_dark:
        outline_path = f'<path d="{path_d}" fill="none" stroke="{outline}" stroke-width="13" stroke-linecap="round"/>'

    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="70" height="70" viewBox="0 0 70 70">
  <!-- Tail Swish Frame {frame} (pivot base at 15, 60) -->
  {outline_path}
  <path d="{path_d}" fill="none" stroke="{coat}" stroke-width="8" stroke-linecap="round"/>
</svg>
"""


